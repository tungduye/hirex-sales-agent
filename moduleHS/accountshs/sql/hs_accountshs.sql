-- Nạp nhanh: toàn bộ dòng của một tập tab dưới dạng JSON dựng trong server (thay acc_json_chunk + 4 luồng của Python).
create or replace function ahs_accounts_json(p_exclude_tabs bigint[] default '{}', p_only_tab bigint default null)
returns text language sql stable as $f$
  select coalesce(json_agg(json_build_object('id', a.id, 'tab_id', a.tab_id, 'dept_id', a.dept_id, 'owner_id', a.owner_id, 'status_id', a.status_id,
           'device_id', a.device_id, 'note', a.note, 'data', a.data, 'created', a.created, 'updated', a.updated) order by a.id)::text, '[]')
  from ahs_accounts a
  where (p_only_tab is null or a.tab_id = p_only_tab)
    and (p_only_tab is not null or not (a.tab_id = any(p_exclude_tabs)));
$f$;

-- Nhập hàng loạt: id dòng khớp khoá (1–2 trường, nối chr(31), strip+lower) — thay pg_idx_fetch.
create or replace function ahs_key_lookup(p_tab bigint, p_fields bigint[], p_keys text[])
returns table(k text, id bigint) language plpgsql stable as $f$
declare ws text := E' \t\n\r\f\v';
begin
  return query execute format(
    'select kx, min(id) from (select id, %s as kx from ahs_accounts where tab_id = $1) z where kx = any($2) group by kx',
    (select string_agg(format('coalesce(lower(btrim(data->>%L, %L)), '''')', f::text, ws), ' || chr(31) || ') from unnest(p_fields) f))
  using p_tab, p_keys;
end $f$;

-- Liên kết (bỏ liên kết chạm tới tab "tải riêng" chưa nạp) — thay 2 truy vấn not exists của get_data_fast / get_tab_rows.
create or replace function ahs_links_json(p_exclude_tabs bigint[] default '{}', p_only_tab bigint default null)
returns text language sql stable as $f$
  select coalesce(json_agg(json_build_object('id', l.id, 'src', l.src, 'dst', l.dst, 'f', l.field_id) order by l.id)::text, '[]')
  from ahs_links l
  where (p_only_tab is null or exists (select 1 from ahs_accounts a where a.id in (l.src, l.dst) and a.tab_id = p_only_tab))
    and not exists (select 1 from ahs_accounts a where a.id = l.src and a.tab_id = any(p_exclude_tabs))
    and not exists (select 1 from ahs_accounts a where a.id = l.dst and a.tab_id = any(p_exclude_tabs));
$f$;

-- Kiểm tra / sửa lỗi dữ liệu (check_db / repair của v7.py).
create or replace function ahs_check_db() returns json language sql stable as $f$
  select json_build_object(
    'integrity', 'ok',
    'orphan_links', (select count(*) from ahs_links where src not in (select id from ahs_accounts) or dst not in (select id from ahs_accounts) or field_id not in (select id from ahs_fields)),
    'cross_links', (select count(*) from ahs_links l join ahs_fields f on f.id = l.field_id join ahs_accounts d on d.id = l.dst where f.link_tab is null or f.link_tab <> d.tab_id),
    'bad_tab', (select count(*) from ahs_accounts where tab_id not in (select id from ahs_tabs)),
    'bad_status', (select count(*) from ahs_accounts where status_id is not null and status_id not in (select id from ahs_statuses)),
    'bad_owner', (select count(*) from ahs_accounts where owner_id is not null and owner_id not in (select id from ahs_owners)),
    'bad_device', (select count(*) from ahs_accounts where device_id is not null and device_id not in (select id from ahs_devices)));
$f$;
create or replace function ahs_repair(p_now double precision) returns json language plpgsql as $f$
begin
  delete from ahs_links where src not in (select id from ahs_accounts) or dst not in (select id from ahs_accounts) or field_id not in (select id from ahs_fields);
  delete from ahs_links where id in (select l.id from ahs_links l join ahs_fields f on f.id = l.field_id join ahs_accounts d on d.id = l.dst where f.link_tab is null or f.link_tab <> d.tab_id);
  update ahs_accounts set status_id = null, updated = p_now where status_id is not null and status_id not in (select id from ahs_statuses);
  update ahs_accounts set owner_id = null, updated = p_now where owner_id is not null and owner_id not in (select id from ahs_owners);
  update ahs_accounts set device_id = null, updated = p_now where device_id is not null and device_id not in (select id from ahs_devices);
  return ahs_check_db();
end $f$;

-- Thống kê dung lượng (db_size của ahs_pg.py).
create or replace function ahs_db_size() returns bigint language sql stable as $f$
  select coalesce(sum(pg_total_relation_size(c.oid)), 0)::bigint from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = current_schema() and c.relkind = 'r' and c.relname like 'ahs\_%';
$f$;

-- Cú vọ: tìm "chứa" không dấu trong toàn bộ dữ liệu (thay chỉ mục FTS5 cục bộ).
create or replace function ahs_search_ids(p_q text, p_limit integer default 2000) returns bigint[] language sql stable as $f$
