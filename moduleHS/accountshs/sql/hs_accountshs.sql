-- Khôi phục từ bản sao lưu .ahs.gz (security definer: service_role không phải chủ bảng nên không tự ALTER TABLE được): tắt trigger lịch sử, xoá sạch ahs_* (bảng khác không đụng), nạp xong thì bật lại + đặt lại sequence.
create or replace function ahs_restore_begin() returns void language plpgsql security definer set search_path = public as $f$
begin
  alter table ahs_accounts disable trigger user;
  alter table ahs_links disable trigger user;
  truncate ahs_depts, ahs_owners, ahs_tabs, ahs_fields, ahs_statuses, ahs_devices, ahs_accounts, ahs_links, ahs_settings, ahs_logs, ahs_tomb, ahs_acc_hist, ahs_cyv_checks;
end $f$;
create or replace function ahs_restore_end() returns void language plpgsql security definer set search_path = public as $f$
declare t text;
begin
  foreach t in array array['ahs_depts','ahs_owners','ahs_tabs','ahs_fields','ahs_statuses','ahs_devices','ahs_accounts','ahs_links','ahs_logs','ahs_acc_hist','ahs_cyv_checks'] loop
    execute format('select setval(pg_get_serial_sequence(%L, ''id''), coalesce((select max(id) from %I), 0) + 1, false)', t, t);
  end loop;
  alter table ahs_accounts enable trigger user;
  alter table ahs_links enable trigger user;
  update ahs_ver set n = n + 1 where id = 1;
end $f$;
revoke all on function ahs_restore_begin(), ahs_restore_end() from public, anon, authenticated;
grant execute on function ahs_restore_begin(), ahs_restore_end() to service_role;

