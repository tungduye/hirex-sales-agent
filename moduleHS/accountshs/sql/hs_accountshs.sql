-- Lịch sử thay đổi (giữ nguyên từ ahs_pg.py)
create or replace function ahs_f_hist_u() returns trigger language plpgsql as $f$
begin
  insert into ahs_acc_hist(acc_id, ts, k, m, data, status_id, owner_id, dept_id, note, device_id) values (old.id, extract(epoch from clock_timestamp()), 'u',
    (old.data is distinct from new.data)::int + 2 * (old.status_id is distinct from new.status_id)::int + 4 * (old.owner_id is distinct from new.owner_id)::int
      + 8 * (old.dept_id is distinct from new.dept_id)::int + 16 * (old.note is distinct from new.note)::int + 32 * (old.device_id is distinct from new.device_id)::int,
    case when old.data is distinct from new.data then old.data::text end, old.status_id, old.owner_id, old.dept_id,
    case when old.note is distinct from new.note then old.note end, old.device_id);
  return null;
end $f$;
create or replace function ahs_f_hist_li() returns trigger language plpgsql as $f$
begin
  insert into ahs_acc_hist(acc_id, ts, k, m, data) values (new.src, extract(epoch from clock_timestamp()), 'l+', 0, json_build_object('f', new.field_id, 't', new.dst)::text);
  return null;
end $f$;
create or replace function ahs_f_hist_ld() returns trigger language plpgsql as $f$
begin
  insert into ahs_acc_hist(acc_id, ts, k, m, data) values (old.src, extract(epoch from clock_timestamp()), 'l-', 0, json_build_object('f', old.field_id, 't', old.dst)::text);
  return null;
end $f$;
create or replace function ahs_f_hist_d() returns trigger language plpgsql as $f$
begin
  if (select v from ahs_settings where k = 'hist_keepdel') is distinct from '1' then delete from ahs_acc_hist where acc_id = old.id; end if;
  return null;
end $f$;
drop trigger if exists ahs_trg_hist_u on ahs_accounts;
