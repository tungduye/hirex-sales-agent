-- Thống kê Vọng gác tính bằng SQL (không nạp từng dòng) — thay core.stats() của Python.
-- p_today = mốc 0h hôm nay (epoch giây, theo giờ VN) do Next truyền xuống để khỏi phụ thuộc tz máy chủ.
create or replace function ahs_cyv_stats(p_ck text, p_tab bigint, p_fid bigint, p_today double precision)
returns json language sql stable as $f$
  with tot as (
    select count(*) n from ahs_accounts
     where p_tab is not null and p_fid is not null and tab_id = p_tab
       and jsonb_typeof(data -> (p_fid::text)) = 'string'
       and length(btrim(data ->> (p_fid::text))) > 0
  ),
  last_res as (
    select res from (
      select res, row_number() over (partition by acc_id order by ts desc) rn
        from ahs_cyv_checks where ck = p_ck and ts >= p_today
    ) z where rn = 1
  ),
  agg as (
    select
      count(*) filter (where res = 'live')  live,
      count(*) filter (where res = 'die')   die,
      count(*) filter (where res = 'error') error,
      count(*) today
    from last_res
  ),
  runs as (select count(*) n from ahs_cyv_checks where ck = p_ck and ts >= p_today)
  select json_build_object(
    'total', coalesce((select n from tot), 0),
    'today', coalesce((select today from agg), 0),
    'live',  coalesce((select live from agg), 0),
    'die',   coalesce((select die from agg), 0),
    'error', coalesce((select error from agg), 0),
    'runs_today', coalesce((select n from runs), 0));
$f$;

